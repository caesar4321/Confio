#!/usr/bin/env node
// Regenerates src/assets/flags/flagXml.ts from a folder of HatScripts/circle-flags
// SVGs (MIT, https://github.com/HatScripts/circle-flags), one `<iso2>.svg` per
// country, lowercase. Download them first, e.g. for each code:
//   curl -sfL -o xx.svg https://raw.githubusercontent.com/HatScripts/circle-flags/gh-pages/flags/xx.svg
// (EU is european_union.svg; a few upstream files are aliases whose body is
// just the target's file name — download the target instead.)
//
// Usage: node scripts/generate-flag-xml.mjs <svg-dir>
//
// Each flag's mask id becomes `flag-<iso>` so several flags on one screen
// never resolve each other's mask. Markup is otherwise copied verbatim; any
// file with scripts, external references or an unexpected shape is refused.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/generate-flag-xml.mjs <svg-dir>');
  process.exit(1);
}

const out = join(dirname(fileURLToPath(import.meta.url)), '../src/assets/flags/flagXml.ts');
const entries = readdirSync(dir)
  .filter(name => /^[a-z]{2}\.svg$/.test(name))
  .sort()
  .map(name => {
    const iso = name.slice(0, 2);
    let svg = readFileSync(join(dir, name), 'utf8').trim();
    const fail = reason => { throw new Error(`${name}: ${reason}`); };
    if (!svg.startsWith('<svg')) fail('not an SVG (alias file? download its target)');
    if (/<script|<image|<foreignObject|\son\w+=|href="(?!#)/i.test(svg)) fail('scripts or external references');
    if ((svg.match(/id="a"/g) || []).length !== 1 || (svg.match(/url\(#a\)/g) || []).length !== 1
      || (svg.match(/\sid="/g) || []).length !== 1) fail('expected exactly one mask id "a"');
    svg = svg.replace('id="a"', `id="flag-${iso}"`).replace('url(#a)', `url(#flag-${iso})`);
    if (svg.includes('`') || svg.includes('${')) fail('unexpected template characters');
    return `  ${iso.toUpperCase()}: \`${svg}\`,`;
  });

// Every country the app lists (utils/countries.ts) plus EU must have a flag:
// an empty or half-downloaded folder must never replace a complete map.
const countriesSource = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '../src/utils/countries.ts'), 'utf8');
const required = new Set([...countriesSource.matchAll(/\['[^']*', '[^']*', '([A-Z]{2})', '/g)].map(m => m[1]));
required.add('EU');
const have = new Set(entries.map(line => line.trim().slice(0, 2)));
const missing = [...required].filter(iso => !have.has(iso));
if (required.size < 200 || missing.length) {
  console.error(`refusing to write: ${missing.length} required flags missing (${missing.slice(0, 20).join(', ')}${missing.length > 20 ? ', …' : ''})`);
  process.exit(1);
}

writeFileSync(out, `// GENERATED by scripts/generate-flag-xml.mjs — do not edit by hand.
// Round flags from HatScripts/circle-flags (MIT, see ./LICENSE.md), keyed by
// ISO 3166-1 alpha-2 (plus EU), rendered with react-native-svg's SvgXml.
export const FLAG_XML: Record<string, string> = {
${entries.join('\n')}
};
`);
console.log(`wrote ${entries.length} flags to ${out}`);
